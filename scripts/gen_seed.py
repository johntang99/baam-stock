"""Render supabase/seed/*.sql from config/*.yaml (single parameter source).

Usage: uv run python scripts/gen_seed.py [--check]
--check exits 1 if the committed seed files differ from what config would generate (used in tests/CI).
All seed rows are configuration, not market data.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

from sr.calendar import get_calendar
from sr.config import load, repo_root

HEADER = "-- AUTO-GENERATED by scripts/gen_seed.py from config/*.yaml. Do not edit; edit config and regenerate.\n"


def lit(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int | float):
        return repr(v)
    if isinstance(v, dict) or (isinstance(v, list) and any(isinstance(x, dict) for x in v)):
        return "'" + json.dumps(v, ensure_ascii=False, sort_keys=True).replace("'", "''") + "'::jsonb"
    if isinstance(v, list):
        inner = ",".join('"' + str(x).replace('"', '\\"') + '"' for x in v)
        return "'{" + inner.replace("'", "''") + "}'"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, rows: list[dict[str, Any]]) -> str:
    if not rows:
        return ""
    cols = list(rows[0].keys())
    vals = ",\n  ".join("(" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)
    return f"insert into {table} ({', '.join(cols)}) values\n  {vals};\n\n"


def sec_key(s: dict[str, Any]) -> str:
    return str(s.get("id") or s["ticker"]).lower()


def build() -> dict[str, str]:
    uni = load("universe")
    bm = load("benchmarks")
    tpl = load("industry_templates")
    srcs = load("data_sources")
    tgts = load("targets")
    sched = load("forecast_schedule")

    secs = uni["securities"]
    by_ticker = {s["ticker"]: s for s in secs}
    companies, securities, idents = [], [], []
    for s in secs:
        k = sec_key(s)
        companies.append({
            "company_id": f"co_{k}", "legal_name": s["legal_name"], "cik": None, "sector": s["sector"],
            "industry": s["industry"], "fiscal_calendar": s.get("fiscal_calendar", {}), "row_version": 1,
        })
        securities.append({
            "security_id": f"sec_{k}", "company_id": f"co_{k}", "security_type": s["type"],
            "primary_exchange": s["exchange"], "currency": "USD", "coverage_tier": s["tier"],
        })
        idents.append({"security_id": f"sec_{k}", "id_type": "ticker", "value": s["ticker"],
                       "valid_from": uni["identifier_valid_from_placeholder"], "valid_to": None})

    peer = bm["semis_peer_v1"]
    defs, versions, updates = [], [], []
    for t in peer["constituents"]:
        if by_ticker[t]["tier"] not in peer["build_for_tiers"]:
            continue
        k = t.lower()
        cons = [c for c in peer["constituents"] if c != t]
        weights = [1 / len(cons)] * len(cons)   # equal weight ex target (D-08), full precision
        defs.append({"benchmark_id": f"bm_semis_peer_ex_{k}", "kind": "peer_basket", "target_security_id": f"sec_{k}",
                     "methodology": peer["methodology"], "missing_rule": peer["missing_rule"]})
        versions.append({
            "benchmark_version_id": f"bmv_semis_peer_ex_{k}_v{peer['version']}", "benchmark_id": f"bm_semis_peer_ex_{k}",
            "version": peer["version"], "effective_from": peer["effective_from"], "effective_to": None,
            "constituents": [{"security_id": f"sec_{c.lower()}", "weight": wt} for c, wt in zip(cons, weights, strict=True)],
            "sync_tolerance_ms": peer["sync_tolerance_ms"], "defined_at": peer["defined_at"],
        })
        updates.append(f"update securities set primary_benchmark_id = 'bm_semis_peer_ex_{k}' where security_id = 'sec_{k}';")
    sx = bm["soxx_ref"]
    defs.append({"benchmark_id": sx["benchmark_id"], "kind": sx["kind"],
                 "target_security_id": None, "methodology": sx["methodology"], "missing_rule": sx["missing_rule"]})
    versions.append({
        "benchmark_version_id": f"bmv_{sx['benchmark_id'][3:]}_v{sx['version']}", "benchmark_id": sx["benchmark_id"],
        "version": sx["version"], "effective_from": sx["effective_from"], "effective_to": None,
        "constituents": [{"security_id": f"sec_{sx['security'].lower()}", "weight": 1.0}],
        "sync_tolerance_ms": peer["sync_tolerance_ms"], "defined_at": sx["defined_at"],
    })
    for s in secs:
        if s["tier"] in sx["reference_for_tiers"]:
            updates.append(f"update securities set reference_benchmark_id = '{sx['benchmark_id']}' "
                           f"where security_id = 'sec_{sec_key(s)}';")

    profiles = []
    semi = tpl["templates"]["semiconductor"]
    for s in secs:
        if s["tier"] != "pilot":
            continue
        k = sec_key(s)
        profiles.append({
            "profile_version_id": f"cpv_{k}_v1", "company_id": f"co_{k}", "version": 1,
            "effective_from": "2026-11-26T00:00:00Z", "key_metrics": semi["key_metrics_default"], "exposures": {},
            "official_sources": {}, "priority_rules_version": "prio-0.1", "industry_template": "semiconductor",
            "valuation_peers": [],
        })

    pilot = HEADER + "-- Securities universe, benchmarks (D-08), company profiles (D-42). Configuration only.\n\n"
    pilot += insert("data_sources", srcs["sources"])
    pilot += insert("companies", companies)
    pilot += insert("securities", securities)
    pilot += insert("security_identifiers", idents)
    pilot += insert("benchmark_definitions", defs)
    pilot += insert("benchmark_versions", versions)
    pilot += "\n".join(updates) + "\n\n"
    pilot += insert("company_profile_versions", profiles)

    templates = HEADER + "-- industry_templates v1 (D-42)\n\n" + insert("industry_templates", [
        {"template_id": tid, "version": tpl["version"], **{k: v for k, v in t.items()}}
        for tid, t in tpl["templates"].items()
    ])

    targets = HEADER + f"-- prediction_targets {tgts['target_definition_version']} and forecast schedule {sched['schedule_version']}\n\n"
    targets += insert("prediction_targets", [{
        "target_row_id": t["target_row_id"], "target_id": t["target_id"],
        "target_definition_version": tgts["target_definition_version"], "track": t["track"], "classes": t["classes"],
        "threshold_rule": t["threshold_rule"], "output_kind": t["output_kind"], "window_rule": t["window_rule"],
        "min_remaining_min": t["min_remaining_min"], "invalid_rules_version": tgts["invalid_rules_version"],
    } for t in tgts["targets"]])
    targets += insert("forecast_schedules", [{
        "schedule_id": sched["schedule_id"], "schedule_version": sched["schedule_version"],
        "effective_from": sched["effective_from"], "effective_to": None, "slots": sched["slots"],
        "half_day_rule": sched["half_day_rule"], "holiday_rule": sched["holiday_rule"], "miss_rule": sched["miss_rule"],
    }])
    cal = get_calendar("XNYS")
    sess = [{
        "exchange": s.exchange, "session_date": s.session_date.isoformat(), "status": s.status,
        "open_at": s.open_at.isoformat().replace("+00:00", "Z") if s.open_at else None,
        "close_at": s.close_at.isoformat().replace("+00:00", "Z") if s.close_at else None,
        "source": s.source, "calendar_version": s.calendar_version,
    } for s in cal.sessions(date(2026, 1, 1), date(2027, 12, 31))]
    sessions = HEADER + "-- trading_sessions XNYS 2026-2027 from sr.calendar (D-04; weekdays incl. holidays as closed)\n\n"
    sessions += insert("trading_sessions", sess)
    return {"0001_pilot.sql": pilot, "0001_templates.sql": templates, "0002_targets_schedule.sql": targets,
            "0003_trading_sessions.sql": sessions}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = repo_root() / "supabase" / "seed"
    out.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, sql in build().items():
        p = Path(out / name)
        if args.check:
            if not p.exists() or p.read_text(encoding="utf-8") != sql:
                stale.append(name)
        else:
            p.write_text(sql, encoding="utf-8")
            print(f"wrote {p.relative_to(repo_root())}")
    if stale:
        print(f"seed out of date (run scripts/gen_seed.py): {stale}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
